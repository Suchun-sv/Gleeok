export type IconName = keyof typeof paths;

/** A glyph on its own (lists, labels), in the text's colour. */
export function Icon({ name, size = 14, className }: { name: IconName; size?: number; className?: string }) {
  return (
    <svg className={`icon ${className ?? ''}`} width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" aria-hidden>
      {paths[name]}
    </svg>
  );
}

export function IconButton({ icon, title, on, onClick, size = 15 }: { icon: IconName; title: string; on?: boolean; onClick: () => void; size?: number }) {
  return (
    <button className={`icon-btn ${on ? 'on' : ''}`} onClick={onClick} title={title} aria-pressed={on}>
      <svg width={size} height={size} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
        {paths[icon]}
      </svg>
    </button>
  );
}

/** Layout switches and the project-settings drawer, at the right end of the main window's last tab strip. */
const COUNT_NAMES = ['', '一', '二', '三', '四', '五', '六'];

/** A box split into n columns, in the same style as the lucide glyphs. */
function Columns({ n }: { n: number }) {
  return (
    <>
      <rect width="18" height="18" x="3" y="3" rx="2" />
      {Array.from({ length: n - 1 }, (_, i) => {
        const x = 3 + (18 * (i + 1)) / n;
        return <path key={i} d={`M${x} 3v18`} />;
      })}
    </>
  );
}

/** One button per pane count the main window can show (2 up to the panes it holds), then focus-expand and settings. */
export function LayoutControls({ visible, max, focusExpand, platform }: { visible: number; max: number; focusExpand: boolean; platform: string }) {
  const mod = platform === 'darwin' ? '⌘⌥' : 'Ctrl+Alt+';
  return (
    <>
      {Array.from({ length: Math.max(0, max - 1) }, (_, i) => i + 2).map((n) => (
        <button
          key={n}
          className={`icon-btn ${Math.min(visible, max) === n ? 'on' : ''}`}
          onClick={() => gleeok.dispatch({ type: 'setVisiblePanes', count: n })}
          title={`${COUNT_NAMES[n]}栏（${mod}Shift+${n}）`}
          aria-pressed={Math.min(visible, max) === n}
        >
          <svg width={15} height={15} viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round">
            <Columns n={n} />
          </svg>
        </button>
      ))}
      <IconButton
        icon="focus"
        on={focusExpand}
        title={`焦点放大：焦点所在的一栏更宽（${mod}F）`}
        onClick={() => gleeok.dispatch({ type: 'toggleFocusExpand' })}
      />
      <span className="trailing-sep" />
      <IconButton icon="panelRight" title={`项目设置：链接、代码、存档（${mod}E）`} onClick={() => gleeok.dispatch({ type: 'toggleEntry' })} />
    </>
  );
}
